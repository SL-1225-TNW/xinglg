const { LocalSaveRepository } = require('../save-repository.js');
const assert = require('node:assert/strict');
const data = new Map();
const storage = { getItem: k => data.get(k) || null, setItem: (k,v) => data.set(k,v) };
const repo = new LocalSaveRepository(storage);
const a = '11111111-1111-4111-8111-111111111111', b = '22222222-2222-4222-8222-222222222222';
const payload = { version: 2, coins: 77, savedAt: 12345 };
storage.setItem('moss-farm-v2', JSON.stringify(payload));
repo.migrateLegacy(p => p.version === 2, () => {});
assert.deepEqual(repo.read().payload, payload);
assert.ok(storage.getItem('moss-farm-v2'));
repo.setIdentity(a); assert.equal(repo.read(), null); repo.write({...payload, coins: 111});
repo.setIdentity(b); assert.equal(repo.read(), null); repo.write({...payload, coins: 222});
repo.setIdentity(a); assert.equal(repo.read().payload.coins,111);
const sent = repo.read(); repo.write({...payload, coins: 112}); repo.ack(sent.sequence, 1);
assert.equal(repo.read().pending,true); assert.equal(repo.read().revision,1);
repo.ack(repo.read().sequence,2); assert.equal(repo.read().pending,false);
repo.setIdentity(null); assert.equal(repo.read().payload.coins,77);
repo.write({version:3, coins:99}); assert.throws(() => repo.write(payload));
assert.throws(() => repo.setIdentity('../other'));
console.log('PASS: legacy preservation, namespaces, future schema, late acknowledgement');
